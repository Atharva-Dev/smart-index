android {
    namespace = "com.kuriousdragon.smartindex"

    defaultConfig {
        applicationId = "com.kuriousdragon.smartindex"
        versionCode = 1
        versionName = "1.0.0"
    }

    buildFeatures {
        buildConfig = true
    }

    // Release signing comes from ~/.gradle/gradle.properties (or -P); never from the repo (LLD — App shell §6.4).
    val signingKeys = listOf(
        "SMARTINDEX_KEYSTORE_FILE",
        "SMARTINDEX_KEYSTORE_PASSWORD",
        "SMARTINDEX_KEY_ALIAS",
        "SMARTINDEX_KEY_PASSWORD",
    ).map { providers.gradleProperty(it).orNull }
    val signingConfigured = signingKeys.all { !it.isNullOrBlank() }

    if (signingConfigured) {
        val (keystoreFile, keystorePassword, alias, aliasPassword) = signingKeys
        signingConfigs.create("release") {
            storeFile = file(keystoreFile!!)
            storePassword = keystorePassword
            keyAlias = alias
            keyPassword = aliasPassword
        }
    } else {
        logger.lifecycle("Smart Index: release signing not configured (see README)")
    }

    buildTypes {
        debug {
            buildConfigField("boolean", "PERF_MARKERS", "true")
        }
        release {
            buildConfigField("boolean", "PERF_MARKERS", "false")
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (signingConfigured) signingConfig = signingConfigs.getByName("release")
        }
        // Macrobenchmark target (LLD — Test & benchmark harness §3.2): release code, debug signing, readable traces.
        create("benchmarkRelease") {
            initWith(getByName("release"))
            signingConfig = signingConfigs.getByName("debug")
            matchingFallbacks += listOf("release")
            isDebuggable = false
            buildConfigField("boolean", "PERF_MARKERS", "true")
            proguardFiles("benchmark-rules.pro") // -dontobfuscate only
        }
    }
}

